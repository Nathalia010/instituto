import assert from 'node:assert/strict';
import fs from 'node:fs';
import {simulate} from '../frontend/src/pages-temporary/demo.ts';
const memory=()=>{const values=new Map();return {getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,String(value)),removeItem:key=>values.delete(key)};};
globalThis.localStorage=memory();globalThis.sessionStorage=memory();
const publicData=JSON.parse(fs.readFileSync(new URL('../publicacion-temporal/contenido-publico.json',import.meta.url),'utf8'));
const original=JSON.stringify(publicData);
assert.throws(()=>simulate('/admin/students',undefined,publicData));
assert.throws(()=>simulate('/login/admin',{username:'adminN',password:'incorrecta'},publicData));
simulate('/login/admin',{username:'adminN',password:'1234987A'},publicData);
assert.equal(simulate('/admin/students',undefined,publicData).length,1);
const book=simulate('/admin/data/courses/validacion/grades',undefined,publicData);
assert.equal(book.rows[0].name,'Estudiante de demostración');
simulate('/admin/data/courses/validacion/grades',{studentId:'demo-estudiante',year:2026,grades:{'Matemáticas':4.7,'Biología':4}},publicData);
simulate('/admin/students/demo-estudiante/access',{active:false},publicData);
assert.throws(()=>simulate('/login/student',{document:'1000000001',issued:'2020-01-15',year:'2026'},publicData));
simulate('/admin/students/demo-estudiante/access',{active:true},publicData);
simulate('/login/student',{document:'1000000001',issued:'2020-01-15',year:'2026'},publicData);
assert.equal(simulate('/student/me',undefined,publicData).notes.find(n=>n.subject==='Matemáticas').grade,4.7);
assert.throws(()=>simulate('/admin/students',undefined,publicData));
assert.throws(()=>simulate('/student/levelings/book',{slotId:'demo-fecha',courseCode:'curso-ajeno',subject:'Biología'},publicData));
simulate('/student/levelings/book',{slotId:'demo-fecha',courseCode:'validacion',subject:'Biología',year:2026,period:'SEGUNDO_SEMESTRE',reason:'Prueba ficticia'},publicData);
assert.equal(simulate('/student/levelings',undefined,publicData).length,1);
simulate('/logout',{},publicData);
assert.throws(()=>simulate('/student/me',undefined,publicData));
assert.equal(JSON.stringify(publicData),original);
console.log('Demo verificada: credenciales, roles simulados, cuenta activa, notas compartidas, nivelación del curso y separación del contenido público.');
